#!/usr/bin/env python3
"""Make the help pages that ChimeraX shows (src/docs/user/tools/) from the Markdown docs.

    python3 scripts/build_help.py

Run it after editing README.md, docs/reference.md or docs/local-prediction.md, and commit the
pages with the Markdown. It needs the 'markdown' package (ChimeraX's own Python has it:
/Applications/ChimeraX-<version>.app/Contents/bin/python3.11 on a Mac). Each page records the
SHA-256 of its Markdown; tests/test_help_pages.py fails when a page is older than its source.

Links between the three documents become links between the pages, images point to
alphalens_images/ (docs/images/*.png, copied into the bundle when it is built, see
pyproject.toml), and links to any other repository file go to GitHub.
"""
import hashlib
import html
import os
import posixpath
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'src', 'docs', 'user', 'tools')
GITHUB = 'https://github.com/KosinskiLab/ChimeraX-AlphaLens/'
IMAGES = 'alphalens_images'

# (Markdown source, page, label in the links at the top of each page)
PAGES = [('README.md', 'alphalens.html', 'AlphaLens'),
         ('docs/reference.md', 'alphalens-reference.html', 'Reference'),
         ('docs/local-prediction.md', 'alphalens-prediction.html', 'Local prediction')]
PAGE_OF = {source: page for source, page, _ in PAGES}

CSS = '''
body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Helvetica, Arial, sans-serif;
       line-height: 1.5; max-width: 54em; margin: 1.2em auto; padding: 0 1em;
       color: #1f2328; background: #ffffff; }
nav { font-size: 0.92em; border-bottom: 1px solid #d0d7de; padding-bottom: 0.5em; margin-bottom: 1em; }
nav a, nav b { margin-right: 1.2em; }
code, pre { font-family: Menlo, Consolas, monospace; font-size: 0.9em; }
code { background: #eff1f3; padding: 0.1em 0.3em; border-radius: 4px; }
pre { background: #f6f8fa; padding: 0.8em; overflow-x: auto; border-radius: 6px; }
pre code { background: none; padding: 0; }
table { border-collapse: collapse; margin: 1em 0; }
th, td { border: 1px solid #d0d7de; padding: 0.3em 0.6em; vertical-align: top; text-align: left; }
th { background: #f6f8fa; }
img { max-width: 100%; height: auto; }
a { color: #0969da; }
@media (prefers-color-scheme: dark) {
  body { color: #e6edf3; background: #0d1117; }
  code { background: #2d333b; }
  pre, th { background: #161b22; }
  th, td, nav { border-color: #30363d; }
  a { color: #4493f8; }
}
'''.strip()

HEADER = re.compile(r'<!-- Generated by scripts/build_help\.py from (\S+) \(sha256 ([0-9a-f]{64})\)')


def sha256(path):
    with open(path, 'rb') as f:
        return hashlib.sha256(f.read()).hexdigest()


def github_slug(value, separator='-'):
    '''Heading ids as GitHub makes them, so that "#getting-a-distogram" links work in both.'''
    value = re.sub(r'[^\w\- ]', '', value.strip().lower())
    return value.replace(' ', separator)


def target(repo_path):
    '''Where a link to a repository file points from a help page.'''
    if repo_path in PAGE_OF:
        return PAGE_OF[repo_path]
    if repo_path.startswith('docs/images/'):
        return f'{IMAGES}/{repo_path[len("docs/images/"):]}'
    kind = 'tree' if os.path.isdir(os.path.join(ROOT, repo_path)) else 'blob'
    return f'{GITHUB}{kind}/main/{repo_path}'


def rewrite_url(url, source):
    '''A link or image URL from the Markdown at repository path source, for the help pages.'''
    if not url or url.startswith('#') or re.match(r'^[a-zA-Z][a-zA-Z0-9+.-]*:', url):
        return url                          # In-page anchor, or a full URL
    path, _, fragment = url.partition('#')
    repo_path = posixpath.normpath(posixpath.join(posixpath.dirname(source), path))
    return target(repo_path) + (f'#{fragment}' if fragment else '')


def rewrite_links(body, source):
    return re.sub(r'(\s(?:href|src)=")([^"]*)(")',
                  lambda m: m.group(1) + html.escape(rewrite_url(html.unescape(m.group(2)), source),
                                                     quote=True) + m.group(3), body)


def page_html(source):
    import markdown
    path = os.path.join(ROOT, source)
    with open(path, encoding='utf-8') as f:
        text = f.read()
    body = markdown.markdown(text, extensions=['tables', 'fenced_code', 'toc'],
                             extension_configs={'toc': {'slugify': github_slug}})
    body = rewrite_links(body, source)
    m = re.search(r'^#\s+(.+)$', text, re.MULTILINE)
    title = m.group(1).strip() if m else 'AlphaLens'
    page = PAGE_OF[source]
    nav = ''.join(f'<b>{label}</b>' if p == page else f'<a href="{p}">{label}</a>'
                  for _, p, label in PAGES)
    return (f'<!-- Generated by scripts/build_help.py from {source} (sha256 {sha256(path)}). '
            f'Edit the Markdown and run the script again. -->\n'
            '<!DOCTYPE html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n'
            f'<title>{html.escape(title)}</title>\n<style>\n{CSS}\n</style>\n</head>\n<body>\n'
            f'<nav>{nav}</nav>\n{body}\n</body>\n</html>\n')


def main():
    os.makedirs(OUT, exist_ok=True)
    for source, page, _ in PAGES:
        with open(os.path.join(OUT, page), 'w', encoding='utf-8', newline='\n') as f:
            f.write(page_html(source))
        print(f'{source} -> {os.path.relpath(os.path.join(OUT, page), ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
